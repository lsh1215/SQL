SELECT COUNT(*) AS COUNT
FROM ECOLI_DATA
WHERE (GENOTYPE & 2) = 0  
  AND ((GENOTYPE & 1) > 0 OR (GENOTYPE & 4) > 0);  
  
# &(AND 연산자) 활용
# 13 & 1 = 1  -- 1번 형질 있음 (1101 & 0001 = 0001)
# 13 & 2 = 0  -- 2번 형질 없음 (1101 & 0010 = 0000)  
# 13 & 4 = 4  -- 3번 형질 있음 (1101 & 0100 = 0100)
# 13 & 8 = 8  -- 4번 형질 있음 (1101 & 1000 = 1000)